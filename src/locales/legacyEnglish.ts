export function translateEnglishValue<T>(value: T): T {
  if (typeof value === 'string') {
    return (LEGACY_EN_TRANSLATIONS[value] ?? value) as T;
  }
  if (Array.isArray(value)) {
    return value.map(item => translateEnglishValue(item)) as T;
  }
  if (value && typeof value === 'object') {
    const translated: Record<string, unknown> = {};
    for (const [key, nested] of Object.entries(value as Record<string, unknown>)) {
      translated[key] = translateEnglishValue(nested);
    }
    return translated as T;
  }
  return value;
}

export function legacyText(locale: Locale, uk: string, ru: string, en?: string): string {
  if (locale === 'uk') return uk;
  if (locale === 'ru') return ru;
  return en ?? LEGACY_EN_TRANSLATIONS[uk] ?? uk;
}

export function legacyValue<T>(locale: Locale, uk: T, ru: T): T {
  if (locale === 'uk') return uk;
  if (locale === 'ru') return ru;
  return translateEnglishValue(uk);
}
